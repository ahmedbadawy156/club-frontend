// Writes shared/config.local.js for local development from the running
// Membership stack (`npx supabase status` in ../club-membership-service).
//
//   npm run config:local
//
// The file is ignored by Git. It holds only the local API address and the
// local publishable key (public by design); nothing is printed.

import { execSync } from "node:child_process";
import { writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const membershipRepo = resolve(root, "..", "club-membership-service");

if (!existsSync(membershipRepo)) {
  console.error(`Membership repository not found at ${membershipRepo}`);
  process.exit(1);
}

let env;
try {
  env = execSync("npx supabase status -o env", {
    cwd: membershipRepo,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
    shell: true,
  });
} catch {
  console.error("Could not read `supabase status`. Is the local stack running?");
  process.exit(1);
}

const values = Object.fromEntries(
  env.split(/\r?\n/)
    .map((line) => line.match(/^([A-Z_]+)="?([^"]*)"?$/))
    .filter(Boolean)
    .map((m) => [m[1], m[2]]),
);

const apiUrl = values.API_URL;
const publishableKey = values.PUBLISHABLE_KEY;
if (!apiUrl || !publishableKey) {
  console.error("API_URL or PUBLISHABLE_KEY missing from `supabase status`.");
  process.exit(1);
}

const config = {
  membership: {
    apiUrl: `${apiUrl}/functions/v1/membership-api`,
    authUrl: `${apiUrl}/auth/v1`,
    publishableKey,
  },
  // Filled in when the Events and Announcements stacks exist.
  events: { apiUrl: "", publishableKey: "" },
  announcements: { apiUrl: "", publishableKey: "" },
};

const out = join(root, "shared", "config.local.js");
writeFileSync(
  out,
  "// Generated by `npm run config:local`. Ignored by Git. Do not commit.\n" +
    `export default ${JSON.stringify(config, null, 2)};\n`,
);
console.log(`Wrote ${out} (membership API at ${config.membership.apiUrl}).`);

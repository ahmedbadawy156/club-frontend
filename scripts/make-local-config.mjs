// Writes shared/config.local.js from the services' Floci deployments. Each
// service's infra/deploy.sh writes its address to infra/out/api.env:
//   ../club-membership-service/infra/out/api.env      (required)
//   ../club-events-service/infra/out/api.env          (optional until deployed)
//   ../club-announcements-service/infra/out/api.env   (optional until deployed)
//
//   npm run config:local
//
// The file holds only API addresses (no keys) and is ignored by Git, because
// each Floci deployment gets its own API id.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

// The API address of one service, or "" when it is not deployed yet.
function apiUrlOf(service) {
  const file = resolve(root, "..", `club-${service}-service`, "infra", "out", "api.env");
  if (!existsSync(file)) return "";
  const values = Object.fromEntries(
    readFileSync(file, "utf8").split(/\r?\n/)
      .map((line) => line.match(/^([A-Z_]+)=(.*)$/))
      .filter(Boolean)
      .map((m) => [m[1], m[2].trim()]),
  );
  // Paths in the pages start after /api, e.g. api("membership", "/auth/login").
  return values.API_URL ? `${values.API_URL}/api` : "";
}

const config = {
  membership: { apiUrl: apiUrlOf("membership") },
  events: { apiUrl: apiUrlOf("events") },
  announcements: { apiUrl: apiUrlOf("announcements") },
};

if (!config.membership.apiUrl) {
  console.error("Membership API address not found. Deploy club-membership-service first (bash infra/deploy.sh there).");
  process.exit(1);
}

const out = join(root, "shared", "config.local.js");
writeFileSync(out,
  "// Generated by `npm run config:local`. Ignored by Git. Holds no keys.\n" +
  `export default ${JSON.stringify(config, null, 2)};\n`);
for (const [service, { apiUrl }] of Object.entries(config)) {
  console.log(`  ${service.padEnd(13)} ${apiUrl || "(not deployed)"}`);
}
console.log(`Wrote ${out}.`);

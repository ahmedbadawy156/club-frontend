// Writes shared/config.local.js from the Membership service's Floci
// deployment (../club-membership-service/infra/out/api.env, written by its
// infra/deploy.sh).
//
//   npm run config:local
//
// The file holds only API addresses (no keys) and is ignored by Git, because
// each Floci deployment gets its own API id.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const membershipEnv = resolve(root, "..", "club-membership-service", "infra", "out", "api.env");

if (!existsSync(membershipEnv)) {
  console.error(`Not found: ${membershipEnv}\nDeploy the Membership service first (bash infra/deploy.sh in club-membership-service).`);
  process.exit(1);
}

const values = Object.fromEntries(
  readFileSync(membershipEnv, "utf8").split(/\r?\n/)
    .map((line) => line.match(/^([A-Z_]+)=(.*)$/))
    .filter(Boolean)
    .map((m) => [m[1], m[2].trim()]),
);
if (!values.API_URL) {
  console.error("API_URL missing from the Membership api.env.");
  process.exit(1);
}

const config = {
  // Paths in the pages start after /api, e.g. api("membership", "/auth/login").
  membership: { apiUrl: `${values.API_URL}/api` },
  // Filled in when the Events and Announcements services are deployed.
  events: { apiUrl: "" },
  announcements: { apiUrl: "" },
};

const out = join(root, "shared", "config.local.js");
writeFileSync(out,
  "// Generated by `npm run config:local`. Ignored by Git. Holds no keys.\n" +
  `export default ${JSON.stringify(config, null, 2)};\n`);
console.log(`Wrote ${out} (membership API at ${config.membership.apiUrl}).`);
